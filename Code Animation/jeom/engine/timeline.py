def _elong(waters):
    """둥근 물방울을 진행 방향으로 길쭉하게(바람에 비스듬히 떨어진 방울): 길이 지나간 자국이 한 획처럼 이어지게."""
    out = []
    for i, (t0, seeds, R, tau) in enumerate(waters):
        if len(seeds) == 1 and 2 <= i < len(waters) - 1:
            (x, y) = seeds[0]
            nx = waters[i + 1][1][0]; px = waters[i - 1][1][-1]
            dx, dy = nx[0] - px[0], nx[1] - px[1]; L = (dx * dx + dy * dy) ** 0.5
            ux, uy = dx / L, dy / L
            h = R * 0.45
            seeds = seg_seeds((x - ux * h, y - uy * h), (x + ux * h, y + uy * h), 1.0)
            R = R * 0.8
        out.append((t0, seeds, R, tau))
    return out


