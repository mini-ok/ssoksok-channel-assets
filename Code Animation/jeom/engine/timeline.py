def gather_scale(t):
    s, frac = 1.0, 0.0
    for tg, sc, fr in GATHER:
        if t >= tg:
            s *= sc; frac = fr
        elif t >= tg - 1 / 12:
            s *= SWELL
            break
        else:
            break
    return s, frac


